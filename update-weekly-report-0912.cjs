const fs = require("fs");
const path = require("path");

const file = path.join(
  process.cwd(),
  "app",
  "report",
  "meta-weekly-share",
  "page.tsx"
);

if (!fs.existsSync(file)) {
  throw new Error("파일을 찾을 수 없음: " + file);
}

let s = fs.readFileSync(file, "utf8");

/* =========================
   백업
========================= */
const backup =
  file + ".bak_" +
  new Date().toISOString().replace(/[:.]/g, "-");

fs.copyFileSync(file, backup);
console.log("백업:", backup);


/* =========================
   1. 보고 기간
========================= */
s = s.replace(
  /2026-08-31\s*~\s*2026-09-06\s*·\s*전주 대비/g,
  "2026-09-06 ~ 2026-09-12 · 전주 대비"
);


/* =========================
   2. 랜딩별 DB 카드
========================= */

/* 눈밑 */
s = s.replace(
  /랜딩 시작일 2026\.08\.25/g,
  "이번주 유입 · 09.06~09.12"
);

s = s.replace(
  /유입 소재\s*최선다해/g,
  "유입 소재 최선다해"
);

/* 눈밑 기존 숫자 6건 → 9건 */
s = s.replace(
  /(눈밑 랜딩[\s\S]{0,500}?)(>6<)([\s\S]{0,100}?건)/,
  '$1>9<$3'
);


/* 코재 */
s = s.replace(
  /랜딩 시작일 2026\.08\.31/g,
  "이번주 유입 · 09.06~09.12"
);

s = s.replace(
  /유입 소재\s*S원장님/g,
  "유입 소재 S원장님"
);

s = s.replace(
  /(코재 랜딩[\s\S]{0,500}?)(>7<)([\s\S]{0,100}?건)/,
  '$1>3<$3'
);


/* 첫코 */
s = s.replace(
  /랜딩 시작일 2026\.08\.11/g,
  "이번주 유입 · 09.06~09.12"
);

s = s.replace(
  /유입 소재\s*타나카/g,
  "유입 소재 타나카"
);

s = s.replace(
  /(첫코 랜딩[\s\S]{0,500}?)(>1<)([\s\S]{0,100}?건)/,
  '$1>3<$3'
);


/* =========================
   3. 남자코 카드 → 전체 DB
========================= */
s = s.replace(
  /랜딩 시작일 2026\.08\.14/g,
  "전주 대비"
);

s = s.replace(
  /남자코 랜딩/g,
  "전체 DB"
);

s = s.replace(
  /유입 소재\s*권태양/g,
  "20건 → 15건"
);

s = s.replace(
  /(전체 DB[\s\S]{0,500}?)(>8<)([\s\S]{0,100}?건)/,
  '$1>15<$3'
);


/* =========================
   4. 이번주 광고비
========================= */

/* 기존 이번 주 광고비 */
s = s.replace(
  /₩1,033,812/g,
  "₩907,867"
);

/* 만약 취소선 마크업 안의 숫자만 있으면 */
s = s.replace(
  /₩907,867\s*<\/s>/g,
  "₩907,867"
);


/* =========================
   5. 9월 누적 광고비
========================= */
s = s.replace(
  /₩922,858/g,
  "₩2,343,231"
);

s = s.replace(
  /9\/1\s*~\s*9\/7 기준/g,
  "9/1 ~ 9/18 기준"
);


/* =========================
   6. 실제 문의(DB)
========================= */
s = s.replace(
  />23건</g,
  ">15건<"
);


/* =========================
   7. DB KPI
========================= */
s = s.replace(
  /(첫코 DB[\s\S]{0,250}?)(>9건<)/,
  '$1>3건<'
);

s = s.replace(
  /(코재 DB[\s\S]{0,250}?)(>7건<)/,
  '$1>3건<'
);

s = s.replace(
  /(눈 DB[\s\S]{0,250}?)(>7건<)/,
  '$1>9건<'
);


/* =========================
   8. 기존에 추가했던
      DB 비교 섹션 값 보정
========================= */
s = s.replace(
  /전체 DB는 20건에서 15건으로 5건 감소했습니다\./g,
  "전체 DB는 20건에서 15건으로 5건 감소했습니다."
);

s = s.replace(
  /코재수술 DB가 7건에서 3건으로 4건 감소\(-57\.1%\)/g,
  "코재수술 DB가 7건에서 3건으로 4건 감소(-57.1%)"
);

s = s.replace(
  /첫코 DB가 9건에서 3건으로 6건 감소\(-66\.7%\)/g,
  "첫코 DB가 9건에서 3건으로 6건 감소(-66.7%)"
);

s = s.replace(
  /눈밑 DB는 4건에서 9건으로 5건 증가\(\+125\.0%\)/g,
  "눈밑 DB는 4건에서 9건으로 5건 증가(+125.0%)"
);


/* =========================
   9. 광고비 비교 문구 삽입
========================= */

const spendSummary = `
              <div className="mt-2 text-xs text-zinc-500">
                전주 비교 ₩855,594 → ₩907,867
                <span className="ml-2 font-semibold text-red-500">
                  +₩52,273 (+6.1%)
                </span>
              </div>
`;

if (
  !s.includes("전주 비교 ₩855,594 → ₩907,867") &&
  s.includes("이번 주 광고비")
) {
  s = s.replace(
    /(이번 주 광고비[\s\S]{0,500}?₩907,867[\s\S]{0,100}?<\/div>)/,
    `$1${spendSummary}`
  );
}


/* =========================
   10. 보고서 요약 문구
========================= */

const summaryMarker = "WEEKLY_META_SUMMARY_20260912";

if (!s.includes(summaryMarker)) {
  const summary = `
        {/* ${summaryMarker} */}
        <div className="mt-6 rounded-2xl border border-zinc-200 bg-white p-5">
          <div className="text-sm font-semibold text-zinc-900">
            주간 핵심 요약
          </div>

          <div className="mt-3 space-y-2 text-sm leading-6 text-zinc-600">
            <p>
              이번 주 광고비는 ₩907,867로 비교 기간 ₩855,594 대비
              ₩52,273 증가(+6.1%)했습니다.
            </p>

            <p>
              전체 DB는 20건에서 15건으로 5건 감소(-25.0%)했습니다.
            </p>

            <p>
              첫코는 타나카 소재에서 3건으로 전주 9건 대비
              6건 감소(-66.7%)했습니다.
            </p>

            <p>
              코재는 S원장님 소재에서 3건으로 전주 7건 대비
              4건 감소(-57.1%)했습니다.
            </p>

            <p>
              눈밑은 최선다해 소재에서 9건으로 전주 4건 대비
              5건 증가(+125.0%)했습니다.
            </p>

            <p>
              9월 1일~18일 누적 광고비는 ₩2,343,231입니다.
            </p>
          </div>
        </div>
`;

  const mainClose = s.lastIndexOf("</main>");

  if (mainClose !== -1) {
    s =
      s.slice(0, mainClose) +
      summary +
      "\n" +
      s.slice(mainClose);
  }
}

fs.writeFileSync(file, s, "utf8");

